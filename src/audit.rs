//! Opt-in launch audit log (phase 5 of docs/connect-proxy-plan.md).
//!
//! One JSONL record per launch, appended when the child exits; when
//! filtered egress is active the proxy threads append CONNECT verdict
//! records through the same supervisor-side handle. The file lives at
//! `~/.local/share/ai-jail/history.jsonl` -- the sandbox never sees it
//! (it is outside every mount).
//!
//! Logging must never break a launch: write errors warn once and are
//! otherwise ignored. The exception is symlink refusal, which is a
//! security decision and gets `security_warn`.
//!
//! Every record is hash-chained over the raw line bytes as written (no
//! JSON canonicalization): each line carries `seq` (its 0-based line
//! index) and `prev` (sha256 of the previous raw line, null at
//! genesis), so `--audit-verify` re-hashes file bytes directly. Legacy
//! v2.x unchained lines need no migration: the first chained record
//! simply links to the sha256 of the previous raw line, whatever it is.

use std::io::Write;
use std::path::Path;
use std::sync::Mutex;
use std::sync::atomic::{AtomicBool, Ordering};
use std::time::{SystemTime, UNIX_EPOCH};

use crate::output;

/// Audit records generated by ai-jail are small. This generous limit keeps a
/// poisoned JSONL file from making any reader retain unbounded memory.
const MAX_JSONL_RECORD_SIZE: usize = 8 * 1024 * 1024;

pub(crate) struct ShowReport {
    pub total: u64,
    pub invalid: u64,
}

/// Open trusted HOME itself as a pinned directory. HOME and its ancestors may
/// be symlinks; after this starting descriptor is pinned, every component below
/// it is opened without following symlinks. O_NONBLOCK prevents special files
/// such as FIFOs from hanging before O_DIRECTORY rejects them.
fn open_home(home: &Path) -> std::io::Result<std::fs::File> {
    use nix::libc;
    use std::os::fd::FromRawFd;
    use std::os::unix::ffi::OsStrExt;

    if home.as_os_str().is_empty() {
        return Err(std::io::Error::new(
            std::io::ErrorKind::InvalidInput,
            "HOME is empty",
        ));
    }
    let path =
        std::ffi::CString::new(home.as_os_str().as_bytes()).map_err(|_| {
            std::io::Error::new(
                std::io::ErrorKind::InvalidInput,
                "HOME contains a NUL byte",
            )
        })?;
    // SAFETY: path is NUL-terminated and open returns a fresh descriptor.
    let fd = unsafe {
        libc::open(
            path.as_ptr(),
            libc::O_RDONLY
                | libc::O_CLOEXEC
                | libc::O_DIRECTORY
                | libc::O_NONBLOCK,
        )
    };
    if fd < 0 {
        return Err(std::io::Error::last_os_error());
    }
    // SAFETY: open returned a fresh descriptor owned by this function.
    Ok(unsafe { std::fs::File::from_raw_fd(fd) })
}

/// Open one entry relative to a pinned directory, without following symlinks.
fn open_entry(
    parent: &std::fs::File,
    name: &std::ffi::CStr,
    flags: nix::libc::c_int,
) -> std::io::Result<std::fs::File> {
    use nix::libc;
    use std::os::fd::{AsRawFd, FromRawFd};

    // SAFETY: parent is live and name is a NUL-terminated C string. No
    // creation flag is used, so openat does not need a mode argument.
    let fd = unsafe {
        libc::openat(
            parent.as_raw_fd(),
            name.as_ptr(),
            libc::O_RDONLY | libc::O_CLOEXEC | libc::O_NOFOLLOW | flags,
        )
    };
    if fd < 0 {
        return Err(std::io::Error::last_os_error());
    }
    // SAFETY: openat returned a fresh descriptor owned by this function.
    Ok(unsafe { std::fs::File::from_raw_fd(fd) })
}

fn validate_log_file_for_uid(
    file: &std::fs::File,
    effective_uid: u32,
) -> std::io::Result<()> {
    use std::io::{Error, ErrorKind};
    use std::os::unix::fs::MetadataExt;

    let metadata = file.metadata()?;
    if !metadata.is_file() {
        return Err(Error::new(
            ErrorKind::InvalidInput,
            "audit log is not a regular file",
        ));
    }
    if metadata.uid() != effective_uid || metadata.mode() & 0o077 != 0 {
        return Err(Error::new(
            ErrorKind::PermissionDenied,
            "audit log must be owned by this user with no group/other permissions",
        ));
    }
    Ok(())
}

fn validate_log_file(file: &std::fs::File) -> std::io::Result<()> {
    // SAFETY: geteuid has no preconditions.
    validate_log_file_for_uid(file, unsafe { nix::libc::geteuid() })
}

/// Safely open the existing audit log relative to a pinned HOME descriptor.
/// A missing component means no log; all symlink/type/security failures are
/// errors. The returned descriptor is the inode readers must continue using.
pub(crate) fn open_history(
    home: &Path,
) -> std::io::Result<Option<std::fs::File>> {
    use nix::libc;
    use std::io::ErrorKind;

    // HOME itself must exist and be a safe directory. Only a missing child
    // component means that the audit log does not exist.
    let mut parent = open_home(home)?;
    for name in [c".local", c"share", c"ai-jail"] {
        parent = match open_entry(
            &parent,
            name,
            libc::O_DIRECTORY | libc::O_NONBLOCK,
        ) {
            Ok(directory) => directory,
            Err(error) if error.kind() == ErrorKind::NotFound => {
                return Ok(None);
            }
            Err(error) => return Err(error),
        };
    }
    let file = match open_entry(&parent, c"history.jsonl", libc::O_NONBLOCK) {
        Ok(file) => file,
        Err(error) if error.kind() == ErrorKind::NotFound => return Ok(None),
        Err(error) => return Err(error),
    };
    validate_log_file(&file)?;
    Ok(Some(file))
}

struct BoundedRecord {
    bytes: Vec<u8>,
    hash: String,
    oversized: bool,
    terminated: bool,
}

/// Read and drain one complete JSONL record while retaining at most
/// MAX_JSONL_RECORD_SIZE bytes. Hashing is incremental, including bytes that
/// are discarded after the cap, and excludes the trailing newline.
fn read_bounded_record(
    reader: &mut impl std::io::BufRead,
) -> std::io::Result<Option<BoundedRecord>> {
    use sha2::Digest;

    let mut bytes = Vec::new();
    let mut hash = sha2::Sha256::new();
    let mut oversized = false;
    let mut saw_data = false;
    loop {
        let available = reader.fill_buf()?;
        if available.is_empty() {
            if !saw_data {
                return Ok(None);
            }
            return Ok(Some(BoundedRecord {
                bytes,
                hash: format!("{:x}", hash.finalize()),
                oversized,
                terminated: false,
            }));
        }
        let newline = available.iter().position(|byte| *byte == b'\n');
        let take = newline.unwrap_or(available.len());
        let chunk = &available[..take];
        saw_data = true;
        hash.update(chunk);
        let remaining = MAX_JSONL_RECORD_SIZE.saturating_sub(bytes.len());
        bytes.extend_from_slice(&chunk[..chunk.len().min(remaining)]);
        if chunk.len() > remaining {
            oversized = true;
        }
        let consumed = take + usize::from(newline.is_some());
        reader.consume(consumed);
        if newline.is_some() {
            return Ok(Some(BoundedRecord {
                bytes,
                hash: format!("{:x}", hash.finalize()),
                oversized,
                terminated: true,
            }));
        }
    }
}

/// Read existing events only. The writer receives one safe line per record;
/// malformed records are marked and counted, and I/O errors propagate.
pub(crate) fn show(
    home: &Path,
    writer: &mut impl Write,
) -> std::io::Result<Option<ShowReport>> {
    let Some(file) = open_history(home)? else {
        return Ok(None);
    };
    show_file(file, writer).map(Some)
}

fn show_file(
    file: std::fs::File,
    writer: &mut impl Write,
) -> std::io::Result<ShowReport> {
    let mut report = ShowReport {
        total: 0,
        invalid: 0,
    };
    let mut reader = std::io::BufReader::new(file);
    while let Some(record) = read_bounded_record(&mut reader)? {
        report.total += 1;
        let summary = if record.oversized {
            None
        } else {
            // serde_json accepts trailing JSON whitespace, so the historical
            // CRLF behavior remains unchanged even though newline framing is
            // removed by the bounded reader.
            serde_json::from_slice::<serde_json::Value>(&record.bytes)
                .ok()
                .and_then(|record| summarize(&record))
        };
        let summary = summary.unwrap_or_else(|| {
            report.invalid += 1;
            format!("[invalid record at line {}]", report.total)
        });
        let mut safe = String::with_capacity(summary.len());
        for ch in summary.chars() {
            // Also escape Unicode bidi controls and line/paragraph separators.
            if ch.is_control()
                || matches!(
                    ch,
                    '\u{061c}'
                        | '\u{200e}'
                        | '\u{200f}'
                        | '\u{2028}'..='\u{202e}'
                        | '\u{2066}'..='\u{2069}'
                )
            {
                safe.extend(ch.escape_default());
            } else {
                safe.push(ch);
            }
        }
        writeln!(writer, "{safe}")?;
    }
    writer.flush()?;
    Ok(report)
}

fn summarize(record: &serde_json::Value) -> Option<String> {
    let ts = record.get("ts")?.as_str()?;
    let kind = record.get("type")?.as_str()?;
    Some(match kind {
        "launch" => {
            let command = record.get("command")?.as_array()?;
            if !command.iter().all(serde_json::Value::is_string) {
                return None;
            }
            let command = serde_json::to_string(command).ok()?;
            let code = record.get("exit_code")?.as_i64()?;
            let duration = record.get("duration_s")?.as_f64()?;
            format!("{ts}  launch {command}  (exit {code}, {duration:.1}s)")
        }
        "connect" => {
            let host = record.get("host")?.as_str()?;
            let port = u16::try_from(record.get("port")?.as_u64()?).ok()?;
            let verdict = record.get("verdict")?.as_str()?;
            let reason = record.get("reason")?.as_str()?;
            format!("{ts}  connect {host}:{port}  {verdict} ({reason})")
        }
        "secret_inject" => {
            let key = record.get("key")?.as_str()?;
            let host = record.get("host")?.as_str()?;
            let count = record.get("substitutions")?.as_u64()?;
            format!("{ts}  credential {key} -> {host}  ({count} substitutions)")
        }
        _ => format!("{ts}  {kind}  (unrecognized audit record)"),
    })
}

/// Append-only JSONL audit log handle. Cheap to share: the proxy
/// threads hold an `Arc<AuditLog>` clone of the supervisor's handle.
pub(crate) struct AuditLog {
    chain: Mutex<ChainState>,
    warned: AtomicBool,
}

struct ChainState {
    file: std::fs::File,
    /// sha256 of the last line written, as lowercase hex.
    prev: Option<String>,
    seq: u64,
    /// The file on disk did not end with a newline (e.g. truncated
    /// tail): the next append must first terminate that remnant, or the
    /// new record would glue onto it.
    needs_newline: bool,
}

/// What one launch record carries. Kept deliberately small: the same
/// capability summary `ai-jail status` prints, not the whole config.
pub(crate) struct LaunchRecord<'a> {
    pub command: &'a [String],
    pub network_mode: &'static str,
    pub allow_hosts: &'a [String],
    pub lockdown: bool,
    pub agent_state: bool,
    pub gpu: bool,
    pub display: bool,
    pub audio: bool,
    pub browser_profile: Option<&'a str>,
    pub project_config: bool,
    pub project_trusted: bool,
    pub global_config: bool,
    pub exit_code: i32,
    pub duration: std::time::Duration,
}

pub(crate) fn sha256_hex(bytes: &[u8]) -> String {
    use sha2::Digest;
    format!("{:x}", sha2::Sha256::digest(bytes))
}

/// Seed the chain from the same inode that will receive appends. Records are
/// bounded in memory and oversized records are still hashed incrementally.
/// Any read failure yields the safe genesis state: logging must never break a
/// launch.
fn seed_chain(file: &std::fs::File) -> (Option<String>, u64, bool) {
    use std::io::{Seek, SeekFrom};

    let Ok(mut file) = file.try_clone() else {
        return (None, 0, false);
    };
    if file.seek(SeekFrom::Start(0)).is_err() {
        return (None, 0, false);
    }
    let mut reader = std::io::BufReader::new(file);
    let mut prev = None;
    let mut seq = 0_u64;
    let mut needs_newline = false;
    loop {
        match read_bounded_record(&mut reader) {
            Ok(Some(record)) => {
                prev = Some(record.hash);
                seq += 1;
                needs_newline = !record.terminated;
            }
            Ok(None) => break,
            Err(_) => return (None, 0, false),
        }
    }
    (prev, seq, needs_newline)
}

fn validate_directory(file: &std::fs::File) -> std::io::Result<()> {
    use nix::libc;
    use std::io::{Error, ErrorKind};
    use std::os::unix::fs::MetadataExt;

    let metadata = file.metadata()?;
    // SAFETY: geteuid has no preconditions.
    if !metadata.is_dir() || metadata.uid() != unsafe { libc::geteuid() } {
        return Err(Error::new(
            ErrorKind::PermissionDenied,
            "audit directory must be a directory owned by this user",
        ));
    }
    Ok(())
}

fn open_or_create_directory(
    parent: &std::fs::File,
    name: &std::ffi::CStr,
) -> std::io::Result<std::fs::File> {
    use nix::libc;
    use std::io::ErrorKind;
    use std::os::fd::AsRawFd;

    let flags = libc::O_DIRECTORY | libc::O_NONBLOCK;
    let directory = match open_entry(parent, name, flags) {
        Ok(directory) => directory,
        Err(error) if error.kind() == ErrorKind::NotFound => {
            // SAFETY: parent and name are valid; mode is used by mkdirat.
            if unsafe {
                libc::mkdirat(parent.as_raw_fd(), name.as_ptr(), 0o700)
            } < 0
            {
                let mkdir_error = std::io::Error::last_os_error();
                if mkdir_error.kind() != ErrorKind::AlreadyExists {
                    return Err(mkdir_error);
                }
            }
            // Re-open after creation (or a racing EEXIST) so no pathname
            // check is trusted and a swapped symlink is rejected.
            open_entry(parent, name, flags)?
        }
        Err(error) => return Err(error),
    };
    validate_directory(&directory)?;
    Ok(directory)
}

fn open_log_for_append(home: &Path) -> std::io::Result<std::fs::File> {
    use nix::libc;
    use std::os::fd::{AsRawFd, FromRawFd};
    use std::os::unix::fs::MetadataExt;

    let mut parent = open_home(home)?;
    validate_directory(&parent)?;
    for name in [c".local", c"share", c"ai-jail"] {
        parent = open_or_create_directory(&parent, name)?;
    }
    // Keep the dedicated audit directory private using its pinned fd.
    // SAFETY: parent is a live descriptor.
    if unsafe { libc::fchmod(parent.as_raw_fd(), 0o700) } < 0 {
        return Err(std::io::Error::last_os_error());
    }

    // SAFETY: parent and name are valid. O_CREAT supplies mode 0600 and the
    // returned descriptor is fresh and owned by this function.
    let fd = unsafe {
        libc::openat(
            parent.as_raw_fd(),
            c"history.jsonl".as_ptr(),
            libc::O_RDWR
                | libc::O_APPEND
                | libc::O_CREAT
                | libc::O_CLOEXEC
                | libc::O_NOFOLLOW
                | libc::O_NONBLOCK,
            0o600,
        )
    };
    if fd < 0 {
        return Err(std::io::Error::last_os_error());
    }
    // SAFETY: openat returned a fresh descriptor.
    let file = unsafe { std::fs::File::from_raw_fd(fd) };
    let metadata = file.metadata()?;
    // SAFETY: geteuid and fchmod have no additional preconditions here.
    if !metadata.is_file() || metadata.uid() != unsafe { libc::geteuid() } {
        return Err(std::io::Error::new(
            std::io::ErrorKind::PermissionDenied,
            "audit log must be a regular file owned by this user",
        ));
    }
    if unsafe { libc::fchmod(file.as_raw_fd(), 0o600) } < 0 {
        return Err(std::io::Error::last_os_error());
    }
    validate_log_file(&file)?;
    Ok(file)
}

fn is_security_open_error(error: &std::io::Error) -> bool {
    use nix::libc;

    matches!(
        error.raw_os_error(),
        Some(
            libc::ELOOP
                | libc::ENOTDIR
                | libc::EISDIR
                | libc::EACCES
                | libc::EPERM
        )
    ) || matches!(
        error.kind(),
        std::io::ErrorKind::InvalidInput | std::io::ErrorKind::PermissionDenied
    )
}

impl AuditLog {
    /// Open the log under trusted `home`, creating descriptor-relative
    /// directories and the file without following symlinks below HOME.
    /// Security failures disable logging with a security warning; ordinary I/O
    /// failures remain best-effort.
    pub(crate) fn open(home: &Path) -> Option<std::sync::Arc<AuditLog>> {
        let path = home.join(".local/share/ai-jail/history.jsonl");
        let file = match open_log_for_append(home) {
            Ok(file) => file,
            Err(error) => {
                let message = format!(
                    "audit log disabled: cannot open {}: {error}",
                    path.display()
                );
                if is_security_open_error(&error) {
                    output::security_warn(&message);
                } else {
                    output::warn(&message);
                }
                return None;
            }
        };
        let (prev, seq, needs_newline) = seed_chain(&file);
        Some(std::sync::Arc::new(AuditLog {
            chain: Mutex::new(ChainState {
                file,
                prev,
                seq,
                needs_newline,
            }),
            warned: AtomicBool::new(false),
        }))
    }

    /// Append one JSON record. Write errors warn once and are dropped:
    /// logging must not break sandboxes.
    ///
    /// The `seq`/`prev` chain fields are inserted here, not in the
    /// record builders, so every record type participates unchanged.
    pub(crate) fn record(&self, entry: serde_json::Value) {
        let mut entry = entry;
        let mut state = self.chain.lock().unwrap();
        if let Some(obj) = entry.as_object_mut() {
            obj.insert("seq".to_string(), state.seq.into());
            obj.insert(
                "prev".to_string(),
                state
                    .prev
                    .as_deref()
                    .map_or(serde_json::Value::Null, |p| p.into()),
            );
        }
        // The chain hashes the raw line bytes as written, without the
        // trailing newline.
        let mut line = entry.to_string();
        let hash = sha256_hex(line.as_bytes());
        line.push('\n');
        if state.needs_newline {
            line.insert(0, '\n');
            state.needs_newline = false;
        }
        let result = state.file.write_all(line.as_bytes());
        if result.is_err() && !self.warned.swap(true, Ordering::SeqCst) {
            output::warn("audit log write failed; further errors suppressed");
        }
        if result.is_ok() {
            state.prev = Some(hash);
            state.seq += 1;
        }
    }
}

/// RFC3339 (UTC, second precision) from std alone -- no chrono. The
/// civil-date conversion is Howard Hinnant's days-from-civil algorithm.
fn rfc3339(now: SystemTime) -> String {
    let secs = now.duration_since(UNIX_EPOCH).unwrap_or_default().as_secs();
    let days = (secs / 86400) as i64;
    let rem = secs % 86400;
    let (hour, min, sec) = (rem / 3600, (rem % 3600) / 60, rem % 60);
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let year = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let day = doy - (153 * mp + 2) / 5 + 1;
    let month = if mp < 10 { mp + 3 } else { mp - 9 };
    let year = if month <= 2 { year + 1 } else { year };
    format!("{year:04}-{month:02}-{day:02}T{hour:02}:{min:02}:{sec:02}Z")
}

/// One launch record: who ran, with which effective capabilities, from
/// which config sources, and how it ended.
pub(crate) fn launch_record(record: &LaunchRecord<'_>) -> serde_json::Value {
    serde_json::json!({
        "ts": rfc3339(SystemTime::now()),
        "type": "launch",
        "command": record.command,
        "network": record.network_mode,
        "allow_hosts": record.allow_hosts,
        "lockdown": record.lockdown,
        "agent_state": record.agent_state,
        "gpu": record.gpu,
        "display": record.display,
        "audio": record.audio,
        "browser_profile": record.browser_profile,
        "config": {
            "project": record.project_config,
            "project_trusted": record.project_trusted,
            "global": record.global_config,
        },
        "exit_code": record.exit_code,
        "duration_s": record.duration.as_millis() as f64 / 1000.0,
    })
}

/// One proxy CONNECT verdict record (filtered egress only).
pub(crate) fn connect_record(
    host: &str,
    port: u16,
    verdict: &str,
    reason: &str,
) -> serde_json::Value {
    serde_json::json!({
        "ts": rfc3339(SystemTime::now()),
        "type": "connect",
        "host": host,
        "port": port,
        "verdict": verdict,
        "reason": reason,
    })
}

/// One phantom-credential substitution record (filtered egress +
/// `--secret`). Names the host, the env var, and the substitution
/// count -- never a value, real or placeholder.
pub(crate) fn secret_inject_record(
    host: &str,
    key: &str,
    substitutions: usize,
) -> serde_json::Value {
    serde_json::json!({
        "ts": rfc3339(SystemTime::now()),
        "type": "secret_inject",
        "host": host,
        "key": key,
        "substitutions": substitutions,
    })
}

/// Outcome of [`verify`]: line counts and the first chain break.
pub(crate) struct VerifyReport {
    /// Lines in the file.
    pub total: u64,
    /// Lines carrying `seq`/`prev` chain fields.
    pub chained: u64,
    /// Valid JSON lines without chain fields (pre-chain records).
    pub legacy: u64,
    /// 1-based number of the first offending line, if any.
    pub first_break: Option<u64>,
}

/// Verify the hash chain of an audit log, line by line (1-based):
///
/// - a line that is not valid JSON is a break (a corrupt record --
///   e.g. a truncated tail) and counts as neither chained nor legacy;
/// - a valid JSON line without both `seq` and `prev` fields is a
///   legacy (pre-chain) record and re-seeds the chain expectation from
///   its own raw bytes;
/// - a chained line breaks when its `prev` is not the sha256 of the
///   previous raw line (genesis, line 1, expects null) or its `seq` is
///   not the line's 0-based index.
///
/// Every expectation is computed from the actual bytes on disk, so a
/// break does not cascade: `first_break` is the first offending line.
pub(crate) fn verify(file: std::fs::File) -> std::io::Result<VerifyReport> {
    let mut reader = std::io::BufReader::new(file);
    let mut report = VerifyReport {
        total: 0,
        chained: 0,
        legacy: 0,
        first_break: None,
    };
    let mut prev_hash: Option<String> = None;
    while let Some(record) = read_bounded_record(&mut reader)? {
        report.total += 1;
        let parsed: Option<serde_json::Value> = if record.oversized {
            None
        } else {
            serde_json::from_slice(&record.bytes).ok()
        };
        let chain_fields =
            parsed.as_ref().and_then(|v| v.as_object()).and_then(|obj| {
                let seq = obj.get("seq")?.as_u64()?;
                let prev = obj.get("prev")?;
                Some((seq, prev))
            });
        match chain_fields {
            None if parsed.is_none() => {
                // Corrupt or oversized record: not verifiable as anything.
                if report.first_break.is_none() {
                    report.first_break = Some(report.total);
                }
            }
            None => {
                report.legacy += 1;
            }
            Some((seq, prev)) => {
                report.chained += 1;
                let prev_matches = match (&prev_hash, prev) {
                    (None, serde_json::Value::Null) => true,
                    (Some(expected), serde_json::Value::String(actual)) => {
                        expected == actual
                    }
                    _ => false,
                };
                let seq_matches = seq == report.total - 1;
                if !(prev_matches && seq_matches)
                    && report.first_break.is_none()
                {
                    report.first_break = Some(report.total);
                }
            }
        }
        prev_hash = Some(record.hash);
    }
    Ok(report)
}

